package com.github.jpmsilva.jsystemd.spring;

import com.github.jpmsilva.jsystemd.StatusProvider;
import org.jspecify.annotations.Nullable;
import org.springframework.boot.info.BuildProperties;
import org.springframework.boot.info.GitProperties;

/**
 * Implementation of {@link StatusProvider} that provides the version of the application that is running, from the build information that Spring Boot
 * exposes: the version of the build, followed by the short id of the commit it was built from, such as {@code Version: 1.4.2 (a1b2c3d)}.
 *
 * <p>The version of the build is the one of the {@link BuildProperties}, which Spring Boot reads from {@code META-INF/build-info.properties}, as generated
 * by the {@code build-info} goal of its Maven plugin, or the {@code buildInfo()} task of its Gradle plugin. The commit is the one of the
 * {@link GitProperties}, read from {@code git.properties}, as generated by the Git commit id plugins of Maven and Gradle. With only one of them, only the
 * version, such as {@code Version: 1.4.2}, or only the commit, such as {@code Version: a1b2c3d}, is reported, and nothing is reported without both.
 *
 * <p>The version never changes while the application runs, so it is read once, when this provider is created.
 *
 * @author Joao Silva
 */
public class BuildInfoStatusProvider implements StatusProvider {

  private final String status;

  /**
   * Creates a new instance, which reports the version of the given build, and the commit it was built from.
   *
   * @param build the build information of the application, or <code>null</code> when it has none
   * @param git the information of the commit the application was built from, or <code>null</code> when it has none
   */
  public BuildInfoStatusProvider(@Nullable BuildProperties build, @Nullable GitProperties git) {
    this.status = status(present(build == null ? null : build.getVersion()), present(git == null ? null : git.getShortCommitId()));
  }

  // a property that is there without a value is the same as one that is not
  private static @Nullable String present(@Nullable String value) {
    return value == null || value.isBlank() ? null : value.strip();
  }

  private static String status(@Nullable String version, @Nullable String commit) {
    if (version == null) {
      return commit == null ? "" : "Version: " + commit;
    }
    return commit == null ? "Version: " + version : "Version: " + version + " (" + commit + ")";
  }

  @Override
  public String status() {
    return status;
  }
}
